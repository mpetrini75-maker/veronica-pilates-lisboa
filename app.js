// Persistent Language Manager
let currentLang = localStorage.getItem('v_pilates_lang') || 'it';
window.currentLang = currentLang;

let selectedDay = 'Mon, Sep 22';
let selectedSlot = '10:00 AM';
let selectedService = "1-on-1 Private Matwork & Reformer Session";

function setLanguage(lang) {
  if (!i18n[lang]) return;
  currentLang = lang;
  window.currentLang = lang;
  localStorage.setItem('v_pilates_lang', lang);

  // Update active state on language switcher buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  // Update document lang
  document.documentElement.lang = lang;

  // Translate all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      // If element has SVG child or complex children, only update text nodes or innerHTML
      if (key.startsWith('pil') && key.includes('_f')) {
        el.innerHTML = i18n[lang][key];
      } else {
        el.textContent = i18n[lang][key];
      }
    }
  });

  // Translate placeholder attributes with data-i18n-ph
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (i18n[lang] && i18n[lang][key]) {
      el.placeholder = i18n[lang][key];
    }
  });

  // Sync Form language selector if present
  const langSelect = document.getElementById('langPreference');
  if (langSelect) langSelect.value = lang;
}

window.setLanguage = setLanguage;

function initLanguage() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const lang = btn.getAttribute('data-lang');
      setLanguage(lang);
    });
  });
  setLanguage(currentLang);
}

// Tab Switcher (Calendly vs WhatsApp)
window.switchBookingTab = function(mode) {
  const tabCal = document.getElementById('tabCalendly');
  const tabWa = document.getElementById('tabWhatsapp');
  const viewCal = document.getElementById('calendlyView');
  const viewWa = document.getElementById('whatsappView');

  if (!tabCal || !tabWa) return;

  if (mode === 'calendly') {
    tabCal.classList.add('active');
    tabWa.classList.remove('active');
    if (viewCal) viewCal.style.display = 'block';
    if (viewWa) viewWa.style.display = 'none';
  } else {
    tabWa.classList.add('active');
    tabCal.classList.remove('active');
    if (viewWa) viewWa.style.display = 'block';
    if (viewCal) viewCal.style.display = 'none';
  }
};

